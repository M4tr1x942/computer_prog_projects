import turtle
t = turtle.Turtle()
turtle.speed(5)
turtle.bgcolor("Cyan")
turtle.speed(0)
def make_ground():
    turtle.color("White")
    turtle.begin_fill()
    turtle.teleport(1000, -600)
    turtle.left(90)
    turtle.forward(300)
    turtle.left(90)
    turtle.forward(2000)
    turtle.left(90)
    turtle.forward(300)
    turtle.left(90)
    turtle.forward(2000)
    turtle.end_fill()
def make_sun():
    turtle.begin_fill()
    turtle.color("Yellow")
    turtle.teleport(0, 350)
    turtle.circle(80)
    turtle.end_fill()
def make_tree():
    turtle.color("Brown")
    turtle.begin_fill()
    for i in range(4):
        turtle.forward(50)
        turtle.left(90)
    turtle.end_fill()
    turtle.color("Cyan")
    turtle.forward(50)
    turtle.left(90)
    turtle.forward(50)
    turtle.color("Green")
    turtle.begin_fill()
    turtle.right(90)
    turtle.forward(50)
    turtle.left(180)
    turtle.forward(50)
    turtle.forward(100)
    turtle.right(120)
    turtle.forward(100)
    turtle.right(60)
    turtle.forward(50)
    turtle.right(60)
    turtle.forward(100)
    turtle.end_fill()
    turtle.begin_fill()
    turtle.left(180)
    turtle.forward(100)
    turtle.left(60)
    turtle.forward(100)
    turtle.right(120)
    turtle.forward(100)
    turtle.right(60)
    turtle.forward(50)
    turtle.right(60)
    turtle.forward(100)
    turtle.right(120)
    turtle.forward(50)
    turtle.end_fill()
    turtle.left(180)
    turtle.forward(50)
    turtle.left(120)
    turtle.forward(100)
    turtle.left(60)
    turtle.begin_fill()
    turtle.forward(100)
    turtle.right(120)
    turtle.forward(150)
    turtle.right(120)
    turtle.forward(150)
    turtle.right(120)
    turtle.forward(50)
    turtle.end_fill()
    turtle.right(180)
def make_cloud():
    turtle.begin_fill()
    turtle.color("Gray")
    turtle.circle(50)
    turtle.end_fill()
    turtle.left(90)
    turtle.forward(50)
    turtle.begin_fill()
    turtle.circle(40)
    turtle.end_fill()
    turtle.left(90)
    turtle.begin_fill()
    turtle.forward(40)
    turtle.circle(20)
    turtle.end_fill()
def make_snowman():
    turtle.color("White")
    turtle.begin_fill()
    turtle.circle(50)
    turtle.end_fill()
    turtle.left(65)
    turtle.begin_fill()
    turtle.forward(100)
    turtle.circle(45)
    turtle.end_fill()
    turtle.left(65)
    turtle.forward(20)
    turtle.right(50)
    turtle.forward(45)
    turtle.begin_fill()
    turtle.circle(35)
    turtle.end_fill()
if __name__ == "__main__":
    make_ground()
    make_sun()
    turtle.teleport(300, -300)
    make_tree()
    turtle.teleport(-300, -300)
    make_tree()
    turtle.teleport(0, 150)
    make_cloud()
    turtle.teleport(300, 150)
    make_cloud()
    turtle.teleport(0, -300)
    make_snowman()
    turtle.teleport(0, 275)
    turtle.color("Green")
    turtle.write("Merry Christmas")
    turtle.done()
